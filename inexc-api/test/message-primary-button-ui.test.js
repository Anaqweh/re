import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import {JSDOM} from 'jsdom';
import {createHarness} from './studio-harness.js';
import {emailFonts,fontStack,fontCSS} from '../message-design.js';
import {renderMail,mailIdentityDefaults} from '../message-mail.js';
import {messageText,messageDirection,richTextPrefix} from '../message-format.js';

const waitFor=async fn=>{for(let i=0;i<250;i++){if(await fn())return;await new Promise(r=>setTimeout(r,20));}throw Error('Expected editor state was not reached');};

test('optional primary button: custom destination, toggle, saved draft, preview and delivery agree',async t=>{
 const h=await createHarness();t.after(()=>h.close());
 const draftId=crypto.randomUUID();
 const initial={designVersion:3,subject:'رسالة الجمعة',message:'جمعة طيبة على قلوبكم',ctaLabel:'استكشف دوراتنا',ctaUrl:'https://example.com/original',audience:'custom',extraRecipients:'teacher@example.com'};
 assert.equal((await h.request('/drafts/'+draftId,'PUT',{version:0,payload:initial})).status,200);
 const dom=new JSDOM('<div class="tabs"><button id="main">مركز الرسائل</button></div><div class="wrap"></div>',{url:h.url,runScripts:'outside-only'}),w=dom.window;
 t.after(()=>w.close());
 Object.assign(w,{fetch,AbortSignal,INEXC_REGISTRATION_ENDPOINT:h.url+'/api',emailFonts,fontStack,fontCSS,renderMail,mailIdentityDefaults,messageText,messageDirection,richTextPrefix,presets:[],newSubscriberIcon:'',createMessageEditor:element=>({element,setTypography(){}})});
 w.sessionStorage.setItem('inexc_do_admin','LOCAL-TEST-ONLY');
 const source=(await fs.readFile(new URL('../../message-studio-ui.js',import.meta.url),'utf8')).replace(/^import .*\n/gm,'').replaceAll('export ','').replaceAll('import.meta.url',JSON.stringify(h.url+'/message-studio-ui.js'));
 w.eval(source);
 const $=s=>w.document.querySelector(s);
 const open=await w.mountMessageStudio($('#main'));await open();
 await waitFor(()=>$('[data-open-draft]'));$('[data-open-draft]').click();
 await waitFor(()=>$('#ms-cta-label').value===initial.ctaLabel);
 const input=(selector,value)=>{const el=$(selector);if(el.type==='checkbox')el.checked=value;else el.value=value;el.dispatchEvent(new w.Event('input',{bubbles:true}));};
 assert.equal($('#ms-cta-enabled').checked,true);assert.equal($('#ms-cta-label').disabled,false);
 input('#ms-cta-label','اقرأ رسالة الجمعة');input('#ms-cta-url','https://example.org/friday?from=email');
 await waitFor(()=>$('#ms-preview-frame').srcdoc.includes('https://example.org/friday?from=email'));
 input('#ms-cta-enabled',false);
 assert.equal($('#ms-cta-label').disabled,true);
 await waitFor(()=>!$('#ms-preview-frame').srcdoc.includes('https://example.org/friday?from=email'));
 input('#ms-cta-enabled',true);
 assert.equal($('#ms-cta-label').value,'اقرأ رسالة الجمعة');
 assert.equal($('#ms-cta-url').value,'https://example.org/friday?from=email');
 await waitFor(async()=>(await h.request('/drafts/'+draftId)).data.payload.ctaLabel==='اقرأ رسالة الجمعة');
 let saved=(await h.request('/drafts/'+draftId)).data.payload;
 const active=await h.request('/preview','POST',{payload:saved});assert.match(active.data.html,/href="https:\/\/example.org\/friday\?from=email"/);
 input('#ms-cta-enabled',false);
 await waitFor(async()=>(await h.request('/drafts/'+draftId)).data.payload.ctaLabel==='');
 saved=(await h.request('/drafts/'+draftId)).data.payload;assert.equal(saved.ctaUrl,'');
 const template=await h.request('/templates/'+crypto.randomUUID(),'PUT',{name:'بدون زر',payload:saved});assert.equal(template.data.cta_label,'');assert.equal(template.data.cta_url,'');
 const preview=await h.request('/preview','POST',{payload:saved});assert.doesNotMatch(preview.data.html,/example.org\/friday/);assert.doesNotMatch(preview.data.text,/اقرأ رسالة الجمعة/);
 const sent=await h.request('/test','POST',{payload:saved,email:'preview@example.com',requestId:crypto.randomUUID()});assert.equal(sent.status,200);assert.equal(h.sent.length,1);assert.doesNotMatch(h.sent[0].html,/example.org\/friday/);
 $('[data-nav="messages"]').click();await waitFor(()=>$('[data-panel="messages"] [data-open-draft]'));$('[data-panel="messages"] [data-open-draft]').click();
 await waitFor(()=>$('#ms-cta-label').value==='');assert.equal($('#ms-cta-enabled').checked,false);
 input('#ms-cta-enabled',true);input('#ms-cta-label','رابط جديد');input('#ms-cta-url','https://example.net/new');
 await waitFor(async()=>(await h.request('/drafts/'+draftId)).data.payload.ctaUrl==='https://example.net/new');
 const reopened=(await h.request('/drafts/'+draftId)).data.payload;assert.equal(reopened.ctaLabel,'رابط جديد');
 assert.equal((await h.request('/review','POST',{payload:{...reopened,ctaUrl:'javascript:alert(1)'}})).data.issues.some(v=>v.includes('رابطه الصحيح')),true);
 assert.equal((await h.query('SELECT count(*)::int AS n FROM email_campaigns')).rows[0].n,0);
});
